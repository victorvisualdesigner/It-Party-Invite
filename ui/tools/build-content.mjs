// Bundles content/*.json into ui/assets/content.js so the design build opens straight from disk
// (browsers block fetch() on file:// URLs). Run after editing any content file:
//   node ui/tools/build-content.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const read = (name) => JSON.parse(readFileSync(join(root, "content", name), "utf8"));

const bundle = {
  copy: read("copy.json"),
  messages: read("invite-messages.json"),
  keyWords: read("key-words.json"),
  noChase: read("no-chase.json"),
};

const out = join(root, "ui", "assets", "content.js");
writeFileSync(
  out,
  "/* Generated by ui/tools/build-content.mjs from content/*.json. Do not edit by hand. */\n" +
    "window.OY_CONTENT = " + JSON.stringify(bundle) + ";\n"
);
console.log("Wrote " + out);
